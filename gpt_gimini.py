def _canon_token(s: str) -> str:
    """
    Приводим строку к каноническому виду для сравнения технологий:
    — нижний регистр;
    — убираем пробелы.
    """
    return "".join(ch for ch in s.lower() if not ch.isspace())


def _extract_candidate_stack(candidate: dict) -> list[str]:
    """
    Достаём стек кандидата из candidate['tech_stack'].

    Поддерживаем варианты:
    — строка "JavaScript, TypeScript, React"
    — список ["JavaScript", "TypeScript, React"]
    — иначе возвращаем пустой список.
    """
    raw = candidate.get("tech_stack", [])
    items: list[str] = []

    if isinstance(raw, str):
        parts = raw.replace(";", ",").split(",")
        items = [p.strip() for p in parts if p.strip()]
    elif isinstance(raw, list):
        for el in raw:
            if isinstance(el, str):
                parts = el.replace(";", ",").split(",")
                items.extend(p.strip() for p in parts if p.strip())

    # убираем дубли, сохраняем порядок
    seen = set()
    result = []
    for it in items:
        key = _canon_token(it)
        if key not in seen:
            seen.add(key)
            result.append(it)
    return result


def build_questions_block(must_have_candidate: list[dict], candidate: dict) -> str:
    """
    Строит готовый блок уточняющих вопросов для кандидата на основе:
    — must_have_candidate: список dict с полями "requirement", "status"
    — candidate: dict, берём из него tech_stack

    Логика (вариант B):
    — Включаем ВСЕ требования, у которых статус не "Да" и не "не относится".
    — Для анкетных пунктов ("Наличие в резюме", "Не указаны зарплатные ожидания") — отдельные шаблоны.
    — Для стеков с перечислением технологий — спрашиваем только те технологии, которых нет в стеке кандидата.
    — Для общих профессиональных требований — задаём вопрос по требованию целиком, с учётом статуса.
    """
    candidate_stack_list = _extract_candidate_stack(candidate)
    candidate_stack_canon = {_canon_token(t) for t in candidate_stack_list}

    NEGATIVE_MARKERS = (
        "нет",
        "частично",
        "требует уточнения",
        "требуется уточнение",
        "не указано",
    )

    issues: list[tuple[str, str]] = []

    for must in must_have_candidate:
        requirement = (must.get("requirement") or "").strip()
        status = (must.get("status") or "").strip()
        if not requirement:
            continue

        status_norm = status.lower()

        # Явное "Да" — пропускаем
        if status_norm == "да":
            continue

        # Спец-случай "не относится" (если такой статус у вас используется)
        if "не относится" in status_norm:
            continue

        # Все статусы с маркерами "нет/частично/требует/не указано" — берём в issues
        if any(marker in status_norm for marker in NEGATIVE_MARKERS):
            issues.append((requirement, status))

    # Убираем дубли требований, сохраняем порядок
    seen_req = set()
    uniq_issues: list[tuple[str, str]] = []
    for req, st in issues:
        if req not in seen_req:
            seen_req.add(req)
            uniq_issues.append((req, st))

    if not uniq_issues:
        return ""  # нет вопросов — блок не нужен

    questions: list[str] = []

    for requirement, status in uniq_issues:
        req_lower = requirement.lower()

        # 1) Анкетные поля / общие данные
        if requirement.startswith("Наличие в резюме:"):
            field = requirement.split(":", 1)[1].strip().lower()

            if "фио" in field:
                q = "просим указать ваше полное ФИО."
            elif "дата рождения" in field:
                q = "просим указать вашу дату рождения."
            elif "локация" in field or "город" in field:
                q = "просим указать вашу текущую локацию (страна и город)."
            else:
                q = f"просим указать: {requirement.split(':', 1)[1].strip()}."
            questions.append(q)
            continue

        if "зарплат" in req_lower:
            q = "просим указать ваши зарплатные ожидания."
            questions.append(q)
            continue

        # 2) Требования по стеку/технологиям:
        #    Пробуем вытащить конкретные технологии из части после двоеточия.
        #    Например:
        #    "Знание стека: Java Script, Type Script, C#"
        #    "Опыт работы с Typescript, Webpack, Git, Docker, Kubernetes, Nginx"
        after_colon = requirement.split(":", 1)[1].strip() if ":" in requirement else requirement
        tech_parts = [p.strip() for p in after_colon.split(",") if p.strip()]

        req_techs: list[tuple[str, str]] = [(p, _canon_token(p)) for p in tech_parts]

        # Отбираем технологии, которых нет в стеке кандидата
        missing_techs: list[str] = []
        for orig, canon in req_techs:
            if canon and canon not in candidate_stack_canon:
                missing_techs.append(orig)

        # Если нашли конкретные недостающие технологии — задаём вопрос только по ним
        if missing_techs:
            if len(missing_techs) == 1:
                tech = missing_techs[0]
                q = (
                    f"просим уточнить, есть ли у вас практический опыт работы с {tech}: "
                    f"на каких проектах вы его использовали и какие задачи решали."
                )
            else:
                joined = ", ".join(missing_techs)
                q = (
                    f"просим уточнить ваш практический опыт работы со следующими технологиями: "
                    f"{joined} (проекты, задачи, роль)."
                )
            questions.append(q)
            continue

        # 3) Общие профессиональные требования (без явного списка технологий)
        status_norm = status.lower()

        if "нет (точно нет)" in status_norm or (
            ("нет" in status_norm)
            and ("требует" not in status_norm)
            and ("частично" not in status_norm)
        ):
            # Жёсткий "нет" — подтверждаем отсутствие опыта и даём окно, если опыт есть
            q = (
                "правильно ли мы понимаем, что у вас пока нет опыта по следующему требованию: "
                f"«{requirement}»? Если такой опыт всё же есть, пожалуйста, опишите проекты и задачи."
            )
        else:
            # Частично / Требует уточнения / Не указано и т. п.
            q = (
                "просим подробнее описать ваш опыт по следующему требованию: "
                f"«{requirement}» — на каких проектах вы это применяли, с какими задачами и инструментами работали."
            )

        questions.append(q)

    # Формируем финальный текст блока
    lines = []
    lines.append("ЧТОБЫ ОЦЕНТЬ ВАШЕ ПОЛНОЕ СООТВЕТСТВИЕ ТРЕБОВАНИЯМ ВАКАНСИИ, ПОЖАЛУЙСТА, УТОЧНИТЕ:")
    for q in questions:
        lines.append(f"— {q}")

    lines.append("")
    lines.append("Также просим подтвердить:")
    lines.append("— готовность к выходу после оффера (сроки);")
    lines.append("— формат оформления (штат, контракт, ИП, самозанятый);")

    return "\n".join(lines)


